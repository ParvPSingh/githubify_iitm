"""Collect results/*.json into results/summary.md and figures in results/figs/."""
import glob
import json
import os

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from common import RES_DIR
from train import SYSTEMS

ARMS = ["scratch", "jepa", "denoise"]
LABEL = {"scratch": "Scratch", "jepa": "JEPA (EMA target)", "denoise": "Denoising"}
COLOR = {"scratch": "#2a78d6", "jepa": "#eb6834", "denoise": "#1baf7a", "teacher": "#8a8a85"}
MARK = {"scratch": "o", "jepa": "s", "denoise": "^"}
FIG = f"{RES_DIR}/figs"
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": "#e4e3dd", "grid.linewidth": 0.6, "lines.linewidth": 2})


def ft_results():
    r = {}
    for p in glob.glob(f"{RES_DIR}/ft_*.json"):
        d = json.load(open(p))
        r[(d["args"]["init"], d["args"]["budget"])] = d["test"]
    return r


def legend(ax):
    ax.legend(frameon=False, fontsize=8)


def main():
    os.makedirs(FIG, exist_ok=True)
    ft = ft_results()
    budgets = sorted({b for _, b in ft})
    jac = json.load(open(f"{RES_DIR}/jacobian_asymmetry.json")) if os.path.exists(f"{RES_DIR}/jacobian_asymmetry.json") else {}
    md = {s: json.load(open(f"{RES_DIR}/md_{s}_b{budgets[-1]}.json")) for s in SYSTEMS
          if os.path.exists(f"{RES_DIR}/md_{s}_b{budgets[-1]}.json")}
    lines = ["# Pilot results (auto-generated by `report.py`)\n"]

    # --- 1. force error vs labels
    fig, axs = plt.subplots(1, 3, figsize=(10, 3.1))
    for ax, s in zip(axs, SYSTEMS):
        for a in ARMS:
            xs = [b for b in budgets if (a, b) in ft]
            ax.plot(xs, [1000 * ft[(a, b)][s]["F_mae"] for b in xs], marker=MARK[a], ms=6, color=COLOR[a], label=LABEL[a])
        ax.set_xscale("log", base=2); ax.set_yscale("log")
        ax.set_title(s); ax.set_xlabel("labelled frames per system")
    axs[0].set_ylabel("test force MAE (meV/Å)"); legend(axs[0])
    fig.tight_layout(); fig.savefig(f"{FIG}/force_mae_vs_labels.png", dpi=160); plt.close(fig)

    lines.append("## Test force MAE (meV/Å) — lower is better\n")
    lines.append("| arm | budget | " + " | ".join(SYSTEMS) + " | mean | rel. RMSE (mean) |")
    lines.append("|---|---|" + "---|" * (len(SYSTEMS) + 2))
    for b in budgets:
        for a in ARMS:
            if (a, b) not in ft:
                continue
            t = ft[(a, b)]
            lines.append(f"| {a} | {b} | " + " | ".join(f"{1000*t[s]['F_mae']:.1f}" for s in SYSTEMS)
                         + f" | {1000*t['mean_F_mae']:.1f} | {np.mean([t[s]['F_rel'] for s in SYSTEMS]):.3f} |")

    # --- 2. Jacobian asymmetry
    if jac:
        fig, axs = plt.subplots(1, 3, figsize=(10, 3.1))
        for ax, s in zip(axs, SYSTEMS):
            for a in ARMS:
                xs = [b for b in budgets if f"{a}_b{b}_s0" in jac]
                ax.plot(xs, [jac[f"{a}_b{b}_s0"][s] for b in xs], marker=MARK[a], ms=6, color=COLOR[a], label=LABEL[a])
            ax.set_xscale("log", base=2); ax.set_title(s); ax.set_xlabel("labelled frames per system")
            ax.set_ylim(bottom=0)
        axs[0].set_ylabel("‖antisym(∂F/∂R)‖ / ‖∂F/∂R‖  (0 = conservative)"); legend(axs[0])
        fig.tight_layout(); fig.savefig(f"{FIG}/jacobian_asymmetry.png", dpi=160); plt.close(fig)
        lines.append("\n## Non-conservativeness: force-Jacobian asymmetry (0 = curl-free)\n")
        lines.append("| arm | budget | " + " | ".join(SYSTEMS) + " | mean |")
        lines.append("|---|---|" + "---|" * (len(SYSTEMS) + 1))
        for b in budgets:
            for a in ARMS:
                k = f"{a}_b{b}_s0"
                if k in jac:
                    lines.append(f"| {a} | {b} | " + " | ".join(f"{jac[k][s]:.3f}" for s in SYSTEMS) + f" | {jac[k]['mean']:.3f} |")

    # --- 3. MD
    if md:
        fig, axs = plt.subplots(2, len(md), figsize=(3.4 * len(md), 5.6), squeeze=False)
        lines.append(f"\n## MD at budget {budgets[-1]} (energy = teacher PE + KE)\n")
        lines.append("Drift = linear-fit slope in meV/atom/ps; ✗ = blew up (T > 6×T0) at the given step.\n")
        strides = sorted({int(k.split("_k")[1]) for k in next(iter(md.values())) if "_k" in k})
        lines.append("| system | arm | " + " | ".join("NVE direct" if k == 0 else f"MTS k={k}" for k in strides) + " |")
        lines.append("|---|---|" + "---|" * len(strides))
        for col, (s, d) in enumerate(md.items()):
            ref = d["reference_teacher"]
            lines.append(f"| {s} | teacher (conservative) | {ref['drift_meV_atom_ps']:+.2f} |" + " |" * (len(strides) - 1))
            ax = axs[0, col]
            E = np.array(ref["E"]); ax.plot(E[:, 0], 1000 * (E[:, 1] - E[0, 1]), color=COLOR["teacher"], label="Teacher (conservative)")
            for a in ARMS:
                r = d[f"{a}_k0"]
                if r["E"]:
                    E = np.array(r["E"]); ax.plot(E[:, 0], 1000 * (E[:, 1] - E[0, 1]), color=COLOR[a], label=LABEL[a])
                cells = []
                for k in strides:
                    rr = d[f"{a}_k{k}"]
                    cells.append(f"✗ @{rr['fail_step']}" if rr["failed"] else f"{rr['drift_meV_atom_ps']:+.2f}")
                lines.append(f"| {s} | {a} | " + " | ".join(cells) + " |")
            ax.set_title(f"{s}: NVE, direct forces only"); ax.set_xlabel("MD step"); ax.set_ylabel("ΔE (meV/atom)")
            ax.set_yscale("symlog", linthresh=1.0)
            ax = axs[1, col]
            ks = [k for k in strides if k > 0]
            for a in ARMS:
                ys = [abs(d[f"{a}_k{k}"]["drift_meV_atom_ps"]) if not d[f"{a}_k{k}"]["failed"] else np.nan for k in ks]
                ax.plot(ks, ys, marker=MARK[a], ms=6, color=COLOR[a], label=LABEL[a])
            ax.axhline(abs(ref["drift_meV_atom_ps"]), color=COLOR["teacher"], ls="--", lw=1.2, label="Teacher NVE")
            ax.set_xscale("log", base=2); ax.set_yscale("log"); ax.set_xlabel("MTS stride k (teacher call every k steps)")
            ax.set_ylabel("|drift| (meV/atom/ps)"); ax.set_title(f"{s}: MTS")
        legend(axs[0, 0]); legend(axs[1, 0])
        fig.tight_layout(); fig.savefig(f"{FIG}/md.png", dpi=160); plt.close(fig)

    # --- 4. pretraining curves
    pre = {m: json.load(open(f"{RES_DIR}/pretrain_{m}.json")) for m in ["jepa", "denoise"] if os.path.exists(f"{RES_DIR}/pretrain_{m}.json")}
    if pre:
        fig, axs = plt.subplots(1, 2, figsize=(7, 2.8))
        for m, d in pre.items():
            L = d["log"]
            axs[0].plot([r["step"] for r in L], [r["loss"] for r in L], color=COLOR[m], label=LABEL[m])
        axs[0].set_yscale("log"); axs[0].set_xlabel("step"); axs[0].set_title("pretraining loss"); legend(axs[0])
        if "jepa" in pre:
            L = pre["jepa"]["log"]
            axs[1].plot([r["step"] for r in L], [r["tgt_std"] for r in L], color=COLOR["jepa"])
            axs[1].set_title("JEPA target-embedding std (collapse check)"); axs[1].set_xlabel("step"); axs[1].set_ylim(bottom=0)
        fig.tight_layout(); fig.savefig(f"{FIG}/pretraining.png", dpi=160); plt.close(fig)

    if os.path.exists(f"{RES_DIR}/timing.json"):
        t = json.load(open(f"{RES_DIR}/timing.json"))
        lines.append("\n## Cost: direct head vs. −∂E/∂R with the same PaiNN (CPU, ms per call)\n")
        lines.append("| atoms | direct | conservative | speed-up |\n|---|---|---|---|")
        for n, v in t.items():
            lines.append(f"| {n} | {v['direct']:.1f} | {v['conservative']:.1f} | {v['speedup']:.2f}× |")
    open(f"{RES_DIR}/summary.md", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
